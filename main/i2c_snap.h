#pragma once
#include "esp_err.h"

// Grove ポート（SDA=IO4, SCL=IO13）の I2C スレーブとして、他のマイコンからスナップを取得できるようにする。
// ESP32 のスレーブはクロックストレッチできないため、「コマンドを書く → 少し待つ → 応答を読む」の 2 段階にする。
//
// 7bit アドレス 0x42。マスターの手順（コマンド書き込みと応答読み出しの間は 2ms 以上あける）:
//   1. 書き込み [0x01]["w=160&h=120&q=20..."]  撮影開始（クエリは HTTP の /image と同じ。空なら既定値）
//   2. 書き込み [0x02] → 読み出し 11 バイト: STATUS
//        [0xA5][state][total u32 LE][w u16 LE][h u16 LE][crc8]
//        state: 0=画像なし 1=撮影中 2=完了 3=エラー。state=2 になるまで繰り返す
//   3. 書き込み [0x03][offset u32 LE][n u8] → 読み出し n+3 バイト: DATA
//        [0xA5][n][data × n][crc8]   n は 1〜120（ESP32 の FIFO は 32 バイトなので 29 以下を推奨）
//   4. offset を進めて total まで繰り返す
// crc8 は多項式 0x07、初期値 0 で、0xA5 の次のバイトから crc8 の直前までを対象にする。
// crc が合わない / 先頭が 0xA5 でないときは、同じ要求をやり直す。
esp_err_t i2c_snap_start(void);
